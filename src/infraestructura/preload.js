const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch, ...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('api', {
  obtenerEstado:        ()        => call('estado:obtener'),
  elegirImportacion:      ()        => call('importar:elegir'),
  importarDesdeArchivo:  (archivo)    => call('importar:desdeRuta', webUtils.getPathForFile(archivo)),
  agregarContrato:     (c)       => call('contrato:agregar', c),
  editarContrato:  (id, c)   => call('contrato:editar', id, c),
  modificarContrato:   (id, f)   => call('contrato:modificar', id, f),
  inactivar:      (id)      => call('contrato:inactivar', id),
  guardarAdmin:       (a)       => call('administracion:guardar', a),
  borrarAdmin:     (id)      => call('administracion:borrar', id),
  guardarMarcas:       (m)       => call('marcas:guardar', m),
  guardarAjuste:      (k, v)    => call('ajuste:guardar', k, v),
  guardarConfig:      (c)       => call('configuracion:guardar', c),
  ponerColorBarraTitulo: (c, tinta) => call('ventana:colorBarraTitulo', c, tinta),
  ponerIconoApp:      (png)     => call('ventana:icono', png),
  ponerZoom:         (f)       => call('ventana:zoom', f),
  consultarIPC:        ()        => call('ipc:consultar'),
  abrirCarpetaDatos:  ()        => call('datos:abrirCarpeta'),
  respaldarAhora:       ()        => call('datos:respaldar'),
  exportarCsv:       ()        => call('datos:exportarCsv'),
  cargarDemo:        ()        => call('importar:demo'),
  descargarModelo: ()       => call('importar:modelo'),
  importarSumar:       ()        => call('importar:sumar'),
  importarReemplazar:   ()        => call('importar:reemplazar'),
  empezarVacio:      ()        => call('inicio:vacio'),
  guardarPropietario:       (o)       => call('propietario:guardar', o),
  borrarPropietario:     (id)      => call('propietario:borrar', id),
  unificarPropietarios:     (k, d)    => call('propietario:unificar', k, d),
  asignarPropietariosContrato: (id, ids) => call('contrato:asignarPropietarios', id, ids),
  ponerCuentaPropietario: (o, d, c) => call('propietario:cuenta', o, d, c),
  agregarDocsPropietario:    (o)       => call('propietario:agregarDocs', o),
  borrarDocPropietario:  (id)      => call('propietario:borrarDoc', id),
  vistaPreviaDoc:      (id)      => call('propietario:vistaPreviaDoc', id),
  abrirDoc:         (id)      => call('propietario:abrirDoc', id),
  deshacerCambio:            ()        => call('deshacer:deshacer'),
  rehacerCambio:            ()        => call('deshacer:rehacer'),
  estadoDeshacer:      ()        => call('deshacer:estado'),
  alCambiarDeshacer:   (cb)      => ipcRenderer.on('deshacer:cambiado', (_e, st) => cb(st)),
  estadoCompartir:     ()        => call('compartir:estado'),
  elegirCarpetaCompartida:       ()        => call('compartir:elegir'),
  publicarCompartido:    ()        => call('compartir:publicar'),
  desactivarCompartir:    ()        => call('compartir:desactivar'),
  alCambiarCompartir:  (cb)      => ipcRenderer.on('compartir:cambiado', (_e, st) => cb(st)),
  alCambiarGuardado:   (cb)      => ipcRenderer.on('guardado:cambiado', (_e, st) => cb(st)),
  visorElegirCarpeta:   ()        => call('visor:elegirCarpeta'),
  visorRecargar:    ()        => call('visor:recargar'),
  alCambiarDatos:   (cb)      => ipcRenderer.on('datos:cambiados', (_e, st) => cb(st)),
});
