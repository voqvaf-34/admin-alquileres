const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch, ...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('api', {
  getState:        ()        => call('state:get'),
  importPick:      ()        => call('import:pick'),
  importFromFile:  (file)    => call('import:fromPath', webUtils.getPathForFile(file)),
  addContract:     (c)       => call('contract:add', c),
  updateContract:  (id, c)   => call('contract:update', id, c),
  patchContract:   (id, f)   => call('contract:patch', id, f),
  inactivate:      (id)      => call('contract:inactivate', id),
  saveAdmin:       (a)       => call('admin:save', a),
  deleteAdmin:     (id)      => call('admin:delete', id),
  saveMarks:       (m)       => call('marks:save', m),
  setSetting:      (k, v)    => call('setting:set', k, v),
  saveConfig:      (c)       => call('config:save', c),
  setTitleBarColor: (c, ink) => call('window:titleBarColor', c, ink),
  fetchIPC:        ()        => call('ipc:fetch'),
  openDataFolder:  ()        => call('data:openFolder'),
  backupNow:       ()        => call('data:backup'),
  exportCsv:       ()        => call('data:exportCsv'),
  loadDemo:        ()        => call('import:demo'),
  startEmpty:      ()        => call('start:empty'),
  saveOwner:       (o)       => call('owner:save', o),
  deleteOwner:     (id)      => call('owner:delete', id),
  mergeOwners:     (k, d)    => call('owner:merge', k, d),
  setContractOwners: (id, ids) => call('contract:setOwners', id, ids),
  setOwnerAccount: (o, d, c) => call('owner:account', o, d, c),
  addOwnerDocs:    (o)       => call('owner:addDocs', o),
  deleteOwnerDoc:  (id)      => call('owner:deleteDoc', id),
  docPreview:      (id)      => call('owner:docPreview', id),
  openDoc:         (id)      => call('owner:openDoc', id),
  undo:            ()        => call('undo:undo'),
  redo:            ()        => call('undo:redo'),
  undoStatus:      ()        => call('undo:status'),
  onUndoChanged:   (cb)      => ipcRenderer.on('undo:changed', (_e, st) => cb(st)),
  shareStatus:     ()        => call('share:status'),
  sharePick:       ()        => call('share:pick'),
  sharePublish:    ()        => call('share:publish'),
  shareDisable:    ()        => call('share:disable'),
  onShareChanged:  (cb)      => ipcRenderer.on('share:changed', (_e, st) => cb(st)),
  onSaveChanged:   (cb)      => ipcRenderer.on('save:changed', (_e, st) => cb(st)),
  viewerPickDir:   ()        => call('viewer:pickDir'),
  viewerReload:    ()        => call('viewer:reload'),
  onDataChanged:   (cb)      => ipcRenderer.on('data:changed', (_e, st) => cb(st)),
});
