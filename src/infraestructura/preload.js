const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch, ...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('api', {
  obtenerEstado:        ()        => call('state:get'),
  elegirImportacion:      ()        => call('import:pick'),
  importarDesdeArchivo:  (archivo)    => call('import:fromPath', webUtils.getPathForFile(archivo)),
  agregarContrato:     (c)       => call('contract:add', c),
  editarContrato:  (id, c)   => call('contract:update', id, c),
  modificarContrato:   (id, f)   => call('contract:patch', id, f),
  inactivar:      (id)      => call('contract:inactivate', id),
  guardarAdmin:       (a)       => call('admin:save', a),
  borrarAdmin:     (id)      => call('admin:delete', id),
  guardarMarcas:       (m)       => call('marks:save', m),
  guardarAjuste:      (k, v)    => call('setting:set', k, v),
  guardarConfig:      (c)       => call('config:save', c),
  ponerColorBarraTitulo: (c, tinta) => call('window:titleBarColor', c, tinta),
  ponerIconoApp:      (png)     => call('window:icon', png),
  ponerZoom:         (f)       => call('window:zoom', f),
  consultarIPC:        ()        => call('ipc:fetch'),
  abrirCarpetaDatos:  ()        => call('data:openFolder'),
  respaldarAhora:       ()        => call('data:backup'),
  exportarCsv:       ()        => call('data:exportCsv'),
  cargarDemo:        ()        => call('import:demo'),
  descargarModelo: ()       => call('import:template'),
  importarSumar:       ()        => call('import:add'),
  importarReemplazar:   ()        => call('import:replace'),
  empezarVacio:      ()        => call('start:empty'),
  guardarPropietario:       (o)       => call('owner:save', o),
  borrarPropietario:     (id)      => call('owner:delete', id),
  unificarPropietarios:     (k, d)    => call('owner:merge', k, d),
  asignarPropietariosContrato: (id, ids) => call('contract:setOwners', id, ids),
  ponerCuentaPropietario: (o, d, c) => call('owner:account', o, d, c),
  agregarDocsPropietario:    (o)       => call('owner:addDocs', o),
  borrarDocPropietario:  (id)      => call('owner:deleteDoc', id),
  vistaPreviaDoc:      (id)      => call('owner:docPreview', id),
  abrirDoc:         (id)      => call('owner:openDoc', id),
  deshacerCambio:            ()        => call('undo:undo'),
  rehacerCambio:            ()        => call('undo:redo'),
  estadoDeshacer:      ()        => call('undo:status'),
  alCambiarDeshacer:   (cb)      => ipcRenderer.on('undo:changed', (_e, st) => cb(st)),
  estadoCompartir:     ()        => call('share:status'),
  elegirCarpetaCompartida:       ()        => call('share:pick'),
  publicarCompartido:    ()        => call('share:publish'),
  desactivarCompartir:    ()        => call('share:disable'),
  alCambiarCompartir:  (cb)      => ipcRenderer.on('share:changed', (_e, st) => cb(st)),
  alCambiarGuardado:   (cb)      => ipcRenderer.on('save:changed', (_e, st) => cb(st)),
  visorElegirCarpeta:   ()        => call('viewer:pickDir'),
  visorRecargar:    ()        => call('viewer:reload'),
  alCambiarDatos:   (cb)      => ipcRenderer.on('data:changed', (_e, st) => cb(st)),
});
